"""A shared TestLookup link unfurls with a title, a description and a card (W25b HYG-09).

``frontend/index.html`` had no Open Graph or Twitter tags, so Slack / Teams /
mail clients showed a bare URL. It now carries seven tags; ``og:image`` must be
an ABSOLUTE URL for unfurlers, and the SPA cannot know its own public origin at
build time, so the tag holds a placeholder that nginx replaces per request
(``sub_filter`` in ``location = /index.html``, from a host-safe map — pinned
config by config in ``test_nginx_configs.py``).

Three things have to agree, and nothing else ties them together:

1. the seven tags, each exactly once, with the pinned values;
2. the card itself: a real 1200 x 630 PNG on the brand background, small
   enough for unfurlers (generated by ``frontend/scripts/make-og-card.mjs``);
3. every nginx config replaces exactly the placeholder ``index.html`` uses
   (a renamed placeholder on one side would ship the literal
   ``__TESTLOOKUP_ORIGIN__`` to every unfurler).

This is a BACKEND test reading the repo, like ``test_frontend_security_headers``:
nothing under ``frontend/`` imports a repo-root file (the image's build context
is ``frontend/`` only).
"""
from __future__ import annotations

import struct
import zlib
from html.parser import HTMLParser
from pathlib import Path

import pytest

# CONFIGS is test_nginx_configs.nginx_configs(): every tracked nginx config,
# enumerated from `git ls-files` (a new config is checked the day it lands).
from tests.regression.test_nginx_configs import (
    CONFIGS,
    OG_PLACEHOLDER,
    _locations,
    _servers,
    parse,
)

pytestmark = pytest.mark.regression

REPO = Path(__file__).resolve().parents[3]
INDEX_HTML = REPO / "frontend" / "index.html"
OG_CARD = REPO / "frontend" / "public" / "og-card.png"

TITLE = "TestLookup — Instant Answers from Your Test Results"
EXPECTED_TAGS = {
    ("property", "og:title"): TITLE,
    ("property", "og:description"): (
        "Test results, failures, flaky tests and release readiness for your projects, in one place."
    ),
    ("property", "og:type"): "website",
    ("property", "og:image"): f"{OG_PLACEHOLDER}/og-card.png",
    ("property", "og:image:width"): "1200",
    ("property", "og:image:height"): "630",
    ("name", "twitter:card"): "summary_large_image",
}
CARD_SIZE = (1200, 630)
CARD_MAX_BYTES = 300 * 1024
BRAND_BACKGROUND = bytes.fromhex("0d1117")  # frontend/public/app-icon.svg
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


class _Head(HTMLParser):
    """Collects ``<meta>`` attributes and the ``<title>`` text. A tag inside an
    HTML comment is a comment to the parser, so prose cannot satisfy a check."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.metas: list[dict[str, str]] = []
        self.title = ""
        self._in_title = False

    def handle_starttag(self, tag, attrs):
        if tag == "meta":
            self.metas.append({k: v or "" for k, v in attrs})
        self._in_title = tag == "title"

    handle_startendtag = handle_starttag

    def handle_endtag(self, tag):
        if tag == "title":
            self._in_title = False

    def handle_data(self, data):
        if self._in_title:
            self.title += data


def _head(text: str | None = None) -> _Head:
    parser = _Head()
    parser.feed(INDEX_HTML.read_text(encoding="utf-8") if text is None else text)
    return parser


def social_tags(head: _Head) -> dict[tuple[str, str], list[str]]:
    """``{(attribute, key): [content, ...]}`` for every og:* / twitter:* tag."""
    found: dict[tuple[str, str], list[str]] = {}
    for meta in head.metas:
        for attribute in ("property", "name"):
            key = meta.get(attribute, "")
            if key.startswith(("og:", "twitter:")):
                found.setdefault((attribute, key), []).append(meta.get("content", ""))
    return found


def test_index_html_carries_the_seven_social_tags_once_each():
    head = _head()
    found = social_tags(head)
    assert set(found) == set(EXPECTED_TAGS), (
        f"missing {sorted(set(EXPECTED_TAGS) - set(found))}, "
        f"unexpected {sorted(set(found) - set(EXPECTED_TAGS))}"
    )
    for key, expected in EXPECTED_TAGS.items():
        assert found[key] == [expected], f"{key}: {found[key]!r}"
    assert head.title == TITLE, "og:title repeats the document <title>"


def test_the_placeholder_appears_only_in_og_image():
    """nginx replaces every occurrence (``sub_filter_once off``): the needle
    must not sit anywhere else in the page, comments included."""
    assert INDEX_HTML.read_text(encoding="utf-8").count(OG_PLACEHOLDER) == 1


def test_the_tag_parser_ignores_commented_tags():
    """Self-test: a commented-out tag is not a tag, and a duplicate is seen."""
    page = (
        '<head><!-- <meta property="og:type" content="website" /> -->'
        '<meta property="og:title" content="a" /><meta property="og:title" content="b">'
        "<title>t</title></head>"
    )
    head = _head(page)
    assert social_tags(head) == {("property", "og:title"): ["a", "b"]}
    assert head.title == "t"


def _chunks(png: bytes) -> list[tuple[bytes, bytes]]:
    out, pos = [], len(PNG_SIGNATURE)
    while pos < len(png):
        (length,) = struct.unpack(">I", png[pos:pos + 4])
        out.append((png[pos + 4:pos + 8], png[pos + 8:pos + 8 + length]))
        pos += 12 + length
    return out


def first_row(png: bytes) -> bytes:
    """The top scanline's pixels, unfiltered. On the first row the "previous
    row" is all zeros, so Up adds nothing and Average / Paeth reduce to the
    left neighbour (Paeth(a, 0, 0) == a, Average adds a // 2)."""
    chunks = _chunks(png)
    width, _height, depth, colour = struct.unpack(">IIBB", chunks[0][1][:10])
    assert depth == 8 and colour in (2, 6), (depth, colour)
    bpp = 3 if colour == 2 else 4
    raw = zlib.decompressobj().decompress(b"".join(data for kind, data in chunks if kind == b"IDAT"))
    kind, line = raw[0], bytearray(raw[1:1 + width * bpp])
    for i in range(len(line)):
        left = line[i - bpp] if i >= bpp else 0
        line[i] = (line[i] + {0: 0, 1: left, 2: 0, 3: left // 2, 4: left}[kind]) & 0xFF
    return bytes(b for i, b in enumerate(line) if i % bpp < 3)


def test_the_card_is_a_1200_by_630_png_on_the_brand_background():
    png = OG_CARD.read_bytes()
    assert png[:8] == PNG_SIGNATURE, "og-card.png is not a PNG"
    assert png[12:16] == b"IHDR"
    assert struct.unpack(">II", png[16:24]) == CARD_SIZE, "og:image:width/height say 1200 x 630"
    assert len(png) < CARD_MAX_BYTES, f"{len(png)} bytes: unfurlers drop large cards"
    row = first_row(png)
    assert row == BRAND_BACKGROUND * CARD_SIZE[0], (
        "the card's top edge is not the #0d1117 brand background "
        "(regenerate with frontend/scripts/make-og-card.mjs)"
    )


def test_the_png_row_reader_unfilters_each_filter_type():
    """Self-test of ``first_row`` on hand-built two-pixel RGB rows."""
    def png_with(filter_type: int, raw_row: bytes) -> bytes:
        ihdr = struct.pack(">IIBBBBB", 2, 1, 8, 2, 0, 0, 0)
        idat = zlib.compress(bytes([filter_type]) + raw_row)

        def chunk(kind: bytes, data: bytes) -> bytes:
            return struct.pack(">I", len(data)) + kind + data + b"\0\0\0\0"

        return PNG_SIGNATURE + chunk(b"IHDR", ihdr) + chunk(b"IDAT", idat) + chunk(b"IEND", b"")

    pixels = bytes([13, 17, 23, 13, 17, 23])
    assert first_row(png_with(0, pixels)) == pixels
    assert first_row(png_with(2, pixels)) == pixels
    assert first_row(png_with(1, bytes([13, 17, 23, 0, 0, 0]))) == pixels
    assert first_row(png_with(4, bytes([13, 17, 23, 0, 0, 0]))) == pixels
    assert first_row(png_with(3, bytes([13, 17, 23, 7, 9, 12]))) == pixels


def test_the_three_frontend_configs_are_enumerated():
    assert {
        "frontend/nginx.conf.template",
        "k8s/overlays/homelab/frontend-nginx-configmap.yaml:default.conf",
        "k8s/overlays/openshift-artifactory/frontend-nginx-configmap.yaml:default.conf",
    } <= set(CONFIGS)


@pytest.mark.parametrize("name", sorted(CONFIGS))
def test_every_nginx_config_replaces_the_placeholder_index_html_uses(name):
    """The cross-file pin: the needle nginx looks for is the one in the page."""
    for server in _servers(parse(CONFIGS[name])):
        index = _locations(server).get("= /index.html")
        assert index is not None, name
        needles = [args[0] for n, args, _ in index if n == "sub_filter"]
        assert needles == [OG_PLACEHOLDER], (name, needles)
    assert f'content="{OG_PLACEHOLDER}/og-card.png"' in INDEX_HTML.read_text(encoding="utf-8")
