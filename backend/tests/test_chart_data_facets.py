@pytest.mark.parametrize("dimension, value", [("branch", None), (None, "main")])
def test_one_half_of_the_pair_is_facet_pair(dimension: Optional[str], value: Optional[str]) -> None:
    with pytest.raises(AnalyticsQueryError) as exc:
        svc.parse_facet(dimension, value)
    assert exc.value.code == "facet_pair"
    assert exc.value.param == "facet_dimension"
    assert exc.value.message == "facet_dimension and facet_value are sent together"


def test_no_facet_is_none() -> None:
    assert svc.parse_facet(None, None) is None


@pytest.mark.parametrize(
    "dimension", ["suite", "release", "project", "day", "test", "", "BRANCH", "branch'; DROP TABLE x; --"],
)
def test_a_dimension_outside_the_five_is_refused_and_never_echoed(dimension: str) -> None:
    with pytest.raises(AnalyticsQueryError) as exc:
        svc.parse_facet(dimension, "main")
    assert exc.value.code == "facet_dimension_enum"
    assert exc.value.param == "facet_dimension"
    assert exc.value.allowed == list(svc.FACET_DIMENSIONS)
    if dimension.strip():
        assert dimension not in exc.value.message


@pytest.mark.parametrize(
    "dimension, value, reason",
    [
        ("branch", "ma\x00in", "facet_value may not contain a NUL character"),
        ("branch", "b" * 2001, "facet_value is 1-2000 characters"),
        ("environment", "", "facet_value is 1-2000 characters"),
        ("branch", svc.OTHER_KEY, "facet_value names a roll-up"),
        ("status", "FAILED", "facet_value is one of the TestStatus vocabulary"),
        ("status", "flaky", "facet_value is one of the TestStatus vocabulary"),
    ],
)
def test_a_bad_value_is_facet_value_with_the_selector_s_reason(
    dimension: str, value: str, reason: str
) -> None:
    with pytest.raises(AnalyticsQueryError) as exc:
        svc.parse_facet(dimension, value)
    assert exc.value.code == "facet_value"
    assert exc.value.param == "facet_value"
    assert exc.value.message.startswith(reason)
    assert "bucket_" not in exc.value.message
    if value.strip() and value != svc.OTHER_KEY:
        assert value not in exc.value.message


def test_a_two_thousand_character_value_is_accepted() -> None:
    assert svc.parse_facet("branch", "b" * 2000) == svc.ChartFacet("branch", "b" * 2000)


@pytest.mark.parametrize("dimension", list(svc.ROW_LEVEL_FACETS))
def test_run_count_under_a_row_level_facet_is_facet_metric_grain(dimension: str) -> None:
    facet = svc.parse_facet(dimension, _value_for(dimension) if dimension == "status" else "product_bug")
    with pytest.raises(AnalyticsQueryError) as exc:
        svc.parse_chart_spec("run_count", ["day"], None, scope=_scope(), facet=facet)
    assert exc.value.code == "facet_metric_grain"
    assert exc.value.param == "facet_dimension"
    assert exc.value.message == (
        "one run holds tests of several statuses (or failure categories), so it "
        "would be counted in more than one panel"
    )
    assert exc.value.allowed == {
        "metric_not": ["run_count"], "row_level_facets": ["status", "failure_category"],
    }


@pytest.mark.parametrize("dimension", ["branch", "environment", "ingestion_source"])
def test_run_count_under_a_run_level_facet_is_accepted(dimension: str) -> None:
    facet = svc.parse_facet(dimension, "main")
    spec = svc.parse_chart_spec("run_count", ["day"], None, scope=_scope(), facet=facet)
    assert spec.facet == facet
    assert svc.grain_for(spec, _scope()) == svc.GRAIN_RUN


@pytest.mark.parametrize("metric", sorted(svc.RUN_ONLY))
def test_a_wall_clock_under_a_row_level_facet_is_run_only_metric(metric: str) -> None:
    for dimension, value in (("status", "failed"), ("failure_category", "product_bug")):
        with pytest.raises(AnalyticsQueryError) as exc:
            svc.parse_chart_spec(
                metric, ["day"], None, scope=_scope(), facet=svc.parse_facet(dimension, value),
            )
        assert exc.value.code == "run_only_metric"
    # A run-level facet keeps the run grain, where the wall clock exists.
    spec = svc.parse_chart_spec(metric, ["day"], None, scope=_scope(), facet=svc.parse_facet("branch", "main"))
    assert svc.grain_for(spec, _scope()) == svc.GRAIN_RUN


def test_every_existing_refusal_keeps_its_precedence_over_the_facet() -> None:
    facet = svc.parse_facet("status", "failed")
    with pytest.raises(AnalyticsQueryError) as exc:
        svc.parse_chart_spec("nope", ["day"], None, scope=_scope(), facet=facet)
    assert exc.value.code == "metric_enum"
    with pytest.raises(AnalyticsQueryError) as exc:
        svc.parse_chart_spec("run_count", ["day", "day"], None, scope=_scope(), facet=facet)
    assert exc.value.code == "unique_dimension"


# ── 3. The identity ─────────────────────────────────────────────────────────


def test_two_panels_differing_only_in_the_value_have_different_identities() -> None:
    scope = _scope()
    main = svc.parse_chart_spec("executions", ["day"], None, scope=scope, facet=svc.parse_facet("branch", "main"))
    dev = svc.parse_chart_spec("executions", ["day"], None, scope=scope, facet=svc.parse_facet("branch", "dev"))
    env = svc.parse_chart_spec("executions", ["day"], None, scope=scope, facet=svc.parse_facet("environment", "main"))
    ids = {svc.cache_identity_parts(scope, spec) for spec in (main, dev, env)}
    assert len(ids) == 3
    assert svc.cache_identity_parts(scope, main)[-1] == "facet=branch=main"


def test_a_request_without_a_facet_keeps_today_s_identity_exactly() -> None:
    scope = _scope(days=14)
    spec = svc.parse_chart_spec("pass_rate", ["day", "suite"], 7, scope=scope)
    assert svc.cache_identity_parts(scope, spec) == (
        "metric=pass_rate",
        "group_by=day,suite",
        "top_n=7",
        "project=11111111-1111-1111-1111-111111111111",
        "release=",
        "suite=",
        "days=14",
    )
    assert spec.facet is None


def _resolved_from_the_route(**overrides) -> dict:
    """``resolved`` as the read layer builds it: EVERY parameter the route
    declares, at its default unless overridden. A renamed facet parameter
    leaves ``facet_dimension`` out, and the panels below collapse."""
    from app.routers import analytics

    signature = inspect.signature(analytics.chart_data.__wrapped__)
    resolved: dict = {}
    for name, param in signature.parameters.items():
        default = param.default
        resolved[name] = getattr(default, "default", default)
    resolved.update(overrides)
    return resolved


def test_the_route_s_identity_hook_reads_the_facet_pair() -> None:
    from app.routers.analytics import _chart_data_identity

    scope = _scope()
    base = dict(metric="executions", group_by=["day"], top_n=None, scope=scope)
    main = _chart_data_identity(_resolved_from_the_route(**base, facet_dimension="branch", facet_value="main"))
    dev = _chart_data_identity(_resolved_from_the_route(**base, facet_dimension="branch", facet_value="dev"))
    none = _chart_data_identity(_resolved_from_the_route(**base))
    assert len({main, dev, none}) == 3
    spec = svc.parse_chart_spec("executions", ["day"], None, scope=scope)
    assert none == svc.cache_identity_parts(scope, spec)


def test_the_route_declares_the_pair_as_single_valued() -> None:
    """A repeated ``facet_value`` is the layer's ``repeated_parameter`` 422."""
    from app.core import analytics_read_layer as layer
    from app.routers import analytics

    single, repeatable = layer.declared_params(analytics.chart_data.__wrapped__)
    assert {"facet_dimension", "facet_value"} <= single
    assert not ({"facet_dimension", "facet_value"} & repeatable)


# ── 4. The statement ────────────────────────────────────────────────────────


def _sql(spec: svc.ChartSpec, scope: AnalyticsScope) -> tuple[str, dict]:
    return svc.build_statement(spec, scope, now=FROZEN)


def test_a_branch_panel_filters_the_run_grain_by_the_chart_s_own_bucket_expression() -> None:
    scope = _scope()
    spec = svc.parse_chart_spec("executions", ["day"], None, scope=scope, facet=svc.parse_facet("branch", "main"))
    sql, params = _sql(spec, scope)
    assert svc.grain_for(spec, scope) == svc.GRAIN_RUN
    assert "FROM test_runs tr" in sql and "test_cases" not in sql
    assert f"AND {svc.DIMENSIONS['branch'].sql} = :bucket_branch" in sql
    assert params["bucket_branch"] == "main"


def test_a_status_panel_reads_rows_and_binds_the_column_s_spelling() -> None:
    scope = _scope()
    spec = svc.parse_chart_spec("executions", ["day"], None, scope=scope, facet=svc.parse_facet("status", "failed"))
    sql, params = _sql(spec, scope)
    assert svc.grain_for(spec, scope) == svc.GRAIN_ROW
    assert "FROM test_cases tc JOIN test_runs tr" in sql
    assert "AND tc.status = :bucket_status" in sql
    assert params["bucket_status"] == "FAILED"
    # The panel's own facet moved the grain; it is stated in definitions.facet.
    assert svc.grain_forced_by(spec, _scope(suite_names=("checkout",))) is None


def test_the_value_is_a_bind_never_text() -> None:
    scope = _scope()
    hostile = "main'; DROP TABLE test_runs; --"
    spec = svc.parse_chart_spec("executions", ["day"], None, scope=scope, facet=svc.parse_facet("branch", hostile))
    sql, params = _sql(spec, scope)
    assert hostile not in sql
    assert params["bucket_branch"] == hostile
    plain = svc.parse_chart_spec("executions", ["day"], None, scope=scope, facet=svc.parse_facet("branch", "x"))
    assert _sql(plain, scope)[0] == sql


def test_no_facet_leaves_the_statement_byte_identical() -> None:
    scope = _scope()
    for metric, dims in (("executions", ("day",)), ("pass_rate", ("day", "suite")), ("run_count", ("branch",))):
        spec = svc.parse_chart_spec(metric, list(dims), None, scope=scope)
        before = svc.ChartSpec(metric=spec.metric, group_by=spec.group_by, top_n=spec.top_n)
        assert _sql(spec, scope) == _sql(before, scope)
        sql, params = _sql(spec, scope)
        assert ":bucket_" not in sql
        assert not [name for name in params if name.startswith("bucket_")]


def test_the_comparability_statement_reads_the_faceted_rows() -> None:
    scope = _scope()
    spec = svc.parse_chart_spec(
        "pass_rate", ["day", "release"], None, scope=scope, facet=svc.parse_facet("branch", "main"),
    )
    sql, params = svc.build_comparability_statement(spec, scope, ["r1", "r2"], now=FROZEN)
    assert f"AND {svc.DIMENSIONS['branch'].sql} = :bucket_branch" in sql
    assert params["bucket_branch"] == "main"


def test_definitions_state_the_facet_only_when_one_is_set() -> None:
    scope = _scope()
    plain = svc.parse_chart_spec("executions", ["day"], None, scope=scope)
    assert "facet" not in svc.definitions(plain, svc.GRAIN_RUN, FROZEN)
    assert "facet_note" not in svc.definitions(plain, svc.GRAIN_RUN, FROZEN)
    panel = svc.parse_chart_spec(
        "executions", ["day"], None, scope=scope, facet=svc.parse_facet("failure_category", "product_bug"),
    )
    out = svc.definitions(panel, svc.GRAIN_ROW, FROZEN)
    assert out["facet"] == {"dimension": "failure_category", "value": "product_bug"}
    assert "execution rows" in out["facet_note"]


