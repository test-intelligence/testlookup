#!/usr/bin/env python3
"""Generate ``frontend/src/components/live/sdkSymbols.json`` from ``client/go`` and ``client/js``.

The /live page's "Connect a test runner" panel shows Go and JavaScript code
(``frontend/src/components/live/sdkSnippets.ts``). Those snippets once called
SDK functions that never existed (``RunWithReporter``, ``NewReporter``,
``createSession``) and named an environment variable the Go client does not
read. ``sdkSnippets.test.ts`` now checks every identifier in them against this
file, and the quality gate (``frontend.sdk-symbols-fresh``) fails when this
file no longer matches the SDK sources, so the two cannot drift apart.

The frontend image builds from ``frontend/`` alone, so the test cannot read
``client/`` itself; this generated list is its copy of the SDK surface.

Usage::

    python scripts/gen_sdk_symbols.py           # rewrite the JSON
    python scripts/gen_sdk_symbols.py --check   # exit 1 when the JSON is stale

Standard library only: the quality-gate CI job installs nothing else.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SYMBOLS_REL = "frontend/src/components/live/sdkSymbols.json"
GO_DIR_REL = "client/go"
JS_DIR_REL = "client/js"

GENERATED_NOTE = (
    "Generated by scripts/gen_sdk_symbols.py from client/go and client/js. "
    "Do not edit: run `python scripts/gen_sdk_symbols.py` after an SDK change."
)


class SdkParseError(Exception):
    """An SDK source no longer has the shape this generator reads."""


# ── Go ───────────────────────────────────────────────────────────────────────

_GO_MODULE = re.compile(r"^module\s+(\S+)", re.M)
_GO_PACKAGE = re.compile(r"^package\s+(\w+)", re.M)
_GO_FUNC = re.compile(r"^func ([A-Z]\w*)\s*[\[(]", re.M)
_GO_METHOD = re.compile(r"^func \(\s*\w+\s+\*?([A-Z]\w*)\s*\)\s*([A-Z]\w*)\s*\(", re.M)
_GO_TYPE = re.compile(r"^type ([A-Z]\w*)\s", re.M)
_GO_STRUCT = re.compile(r"^type ([A-Z]\w*) struct \{\n(.*?)^\}", re.M | re.S)
_GO_FIELD = re.compile(r"^\t([A-Z]\w*(?:\s*,\s*[A-Z]\w*)*)\s+[^\s/=]", re.M)
_GO_DECL_BLOCK = re.compile(r"^(?:const|var) \(\n(.*?)^\)", re.M | re.S)
_GO_BLOCK_NAME = re.compile(r"^\t([A-Z]\w*)\b", re.M)
_GO_SINGLE_DECL = re.compile(r"^(?:const|var) ([A-Z]\w*)\b", re.M)
# The variables New / NewFromEnv / StartSession read. LoadConfig's overlay()
# names (TESTLOOKUP_PROJECT, TESTLOOKUP_API_KEY, ...) are left out on purpose:
# New never reads them, and a snippet that sets one configures nothing.
_GO_ENV = re.compile(r"\b(?:env|get)\(\s*\"(TESTLOOKUP_[A-Z0-9_]+)\"")


def _go_symbols(root: Path) -> dict[str, object]:
    go_dir = root / GO_DIR_REL
    go_mod = go_dir / "go.mod"
    if not go_mod.is_file():
        raise SdkParseError(f"{GO_DIR_REL}/go.mod is missing")
    module_match = _GO_MODULE.search(go_mod.read_text(encoding="utf-8"))
    if not module_match:
        raise SdkParseError(f"{GO_DIR_REL}/go.mod declares no module")
    module = module_match.group(1)

    pkg_dir = go_dir / "testlookup"
    sources = sorted(
        p for p in pkg_dir.glob("*.go") if not p.name.endswith("_test.go")
    )
    if not sources:
        raise SdkParseError(f"{GO_DIR_REL}/testlookup has no Go sources")

    package = ""
    functions: set[str] = set()
    types: set[str] = set()
    constants: set[str] = set()
    methods: dict[str, set[str]] = {}
    fields: dict[str, set[str]] = {}
    env: set[str] = set()
    for path in sources:
        text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        pkg_match = _GO_PACKAGE.search(text)
        if pkg_match:
            package = pkg_match.group(1)
        functions.update(_GO_FUNC.findall(text))
        types.update(_GO_TYPE.findall(text))
        for receiver, name in _GO_METHOD.findall(text):
            methods.setdefault(receiver, set()).add(name)
        for struct_name, body in _GO_STRUCT.findall(text):
            names = fields.setdefault(struct_name, set())
            for group in _GO_FIELD.findall(body):
                names.update(part.strip() for part in group.split(","))
        for body in _GO_DECL_BLOCK.findall(text):
            constants.update(_GO_BLOCK_NAME.findall(body))
        constants.update(_GO_SINGLE_DECL.findall(text))
        env.update(_GO_ENV.findall(text))

    if not package:
        raise SdkParseError(f"{GO_DIR_REL}/testlookup declares no package")
    for required in ("Config", "SessionOptions", "RecordOptions"):
        if required not in fields:
            raise SdkParseError(f"Go struct {required} was not found")

    return {
        "module": module,
        "package": package,
        "import_path": f"{module}/{pkg_dir.name}",
        "functions": sorted(functions),
        "types": sorted(types),
        "constants": sorted(constants),
        "methods": {k: sorted(v) for k, v in sorted(methods.items())},
        "fields": {k: sorted(v) for k, v in sorted(fields.items())},
        "env": sorted(env),
    }


# ── JavaScript / TypeScript ──────────────────────────────────────────────────

_TS_EXPORT = re.compile(
    r"^export\s+(?:declare\s+)?(?:abstract\s+)?(?:async\s+)?"
    r"(?:class|function|const|let|interface|type|enum)\s+(\w+)",
    re.M,
)
_TS_CLASS = re.compile(r"^export\s+(?:default\s+)?class\s+(\w+)[^{]*\{\n(.*?)^\}", re.M | re.S)
# Public members sit at a two-space indent; private / protected ones and the
# constructor are not part of what a snippet may call.
_TS_MEMBER = re.compile(
    r"^  (?!private\b|protected\b|constructor\b)"
    r"(?:public\s+)?(?:static\s+)?(?:async\s+)?(?:get\s+|set\s+)?(?:readonly\s+)?"
    r"(\w+)\s*[(<:?]",
    re.M,
)
_TS_INTERFACE = re.compile(r"^(?:export\s+)?interface\s+(\w+)[^{]*\{\n(.*?)^\}", re.M | re.S)
_TS_FIELD = re.compile(r"^  (\w+)\??\s*:", re.M)
_MOCHA_OPTIONS = re.compile(r"^  reporterOptions\??\s*:\s*\{\n(.*?)^  \}", re.M | re.S)
_MOCHA_FIELD = re.compile(r"^    (\w+)\??\s*:", re.M)
_JS_ENV = re.compile(r"^\s+(TESTLOOKUP_[A-Z0-9_]+)\s*:", re.M)
_JEST_OPTIONS_INTERFACE = "TestLookupJestReporterOptions"


def _read_ts(path: Path) -> str:
    if not path.is_file():
        raise SdkParseError(f"{path.name} is missing from {JS_DIR_REL}/src")
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def _js_symbols(root: Path) -> dict[str, object]:
    js_dir = root / JS_DIR_REL
    pkg_path = js_dir / "package.json"
    if not pkg_path.is_file():
        raise SdkParseError(f"{JS_DIR_REL}/package.json is missing")
    pkg = json.loads(pkg_path.read_text(encoding="utf-8"))
    exports_map = pkg.get("exports") or {}
    if "." not in exports_map:
        raise SdkParseError(f"{JS_DIR_REL}/package.json exports no '.' entry")

    def _source_of(entry: object) -> Path:
        target = entry.get("default") if isinstance(entry, dict) else entry
        if not isinstance(target, str):
            raise SdkParseError(f"unreadable export entry {entry!r}")
        return js_dir / "src" / (Path(target).stem + ".ts")

    main_text = _read_ts(_source_of(exports_map["."]))
    subpaths = sorted(
        key[2:] for key in exports_map
        if key.startswith("./") and not key.endswith(".json")
    )

    members: dict[str, list[str]] = {}
    for name, body in _TS_CLASS.findall(main_text):
        members[name] = sorted(set(_TS_MEMBER.findall(body)))
    fields: dict[str, list[str]] = {}
    for name, body in _TS_INTERFACE.findall(main_text):
        if re.search(rf"^export\s+interface\s+{name}\b", main_text, re.M):
            fields[name] = sorted(set(_TS_FIELD.findall(body)))
    for required in ("ReporterConfig", "SessionOptions", "RecordOptions"):
        if required not in fields:
            raise SdkParseError(f"JS interface {required} was not found")

    jest_text = _read_ts(js_dir / "src" / "jest-reporter.ts")
    jest_options = [
        sorted(set(_TS_FIELD.findall(body)))
        for name, body in _TS_INTERFACE.findall(jest_text)
        if name == _JEST_OPTIONS_INTERFACE
    ]
    if not jest_options:
        raise SdkParseError(f"jest-reporter.ts has no {_JEST_OPTIONS_INTERFACE}")

    mocha_text = _read_ts(js_dir / "src" / "mocha-reporter.ts")
    mocha_block = _MOCHA_OPTIONS.search(mocha_text)
    if not mocha_block:
        raise SdkParseError("mocha-reporter.ts has no reporterOptions block")

    env: set[str] = set()
    for path in sorted((js_dir / "src").glob("*.ts")):
        env.update(_JS_ENV.findall(_read_ts(path)))

    return {
        "package": pkg.get("name", ""),
        "version": pkg.get("version", ""),
        "subpaths": subpaths,
        "exports": sorted(set(_TS_EXPORT.findall(main_text))),
        "members": dict(sorted(members.items())),
        "fields": dict(sorted(fields.items())),
        "jest_options": jest_options[0],
        "mocha_options": sorted(set(_MOCHA_FIELD.findall(mocha_block.group(1)))),
        "env": sorted(env),
    }


# ── Entry points ─────────────────────────────────────────────────────────────


def build_symbols(root: Path = REPO_ROOT) -> dict[str, object]:
    """The SDK surface the /live snippets may use, read from ``root``."""
    return {
        "_generated": GENERATED_NOTE,
        "go": _go_symbols(root),
        "js": _js_symbols(root),
    }


def render(symbols: dict[str, object]) -> str:
    return json.dumps(symbols, indent=2, sort_keys=True) + "\n"


def stale_problems(root: Path = REPO_ROOT) -> list[str]:
    """Why the committed JSON does not match the SDK sources ([] when fresh).

    The comparison is on parsed JSON, not bytes, so a formatter that rewraps
    the file (prettier runs over frontend/src) does not make it stale."""
    try:
        expected = build_symbols(root)
    except SdkParseError as exc:
        return [f"cannot read the SDK sources: {exc}"]
    path = root / SYMBOLS_REL
    if not path.is_file():
        return [f"{SYMBOLS_REL} is missing"]
    try:
        current = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        return [f"{SYMBOLS_REL} is not valid JSON: {exc}"]
    if current == expected:
        return []
    problems: list[str] = []
    for lang in ("go", "js"):
        want = expected.get(lang) or {}
        have = (current.get(lang) or {}) if isinstance(current, dict) else {}
        if not isinstance(want, dict) or not isinstance(have, dict):
            continue
        for key in sorted(set(want) | set(have)):
            if want.get(key) != have.get(key):
                problems.append(f"{lang}.{key} differs from the SDK sources")
    return problems or [f"{SYMBOLS_REL} differs from the SDK sources"]


def write(root: Path = REPO_ROOT) -> Path:
    path = root / SYMBOLS_REL
    path.parent.mkdir(parents=True, exist_ok=True)
    # Bytes, not write_text: on Windows write_text turns \n into \r\n.
    path.write_bytes(render(build_symbols(root)).encode("utf-8"))
    return path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true",
        help="exit 1 when the committed JSON does not match the SDK sources",
    )
    args = parser.parse_args(argv)
    if args.check:
        problems = stale_problems()
        for problem in problems:
            print(f"{SYMBOLS_REL}: {problem}", file=sys.stderr)
        if problems:
            print("Run: python scripts/gen_sdk_symbols.py", file=sys.stderr)
        return 1 if problems else 0
    try:
        path = write()
    except SdkParseError as exc:
        print(f"cannot read the SDK sources: {exc}", file=sys.stderr)
        return 1
    print(f"wrote {path.relative_to(REPO_ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
